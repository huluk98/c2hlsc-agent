def render_makefile(config: AgentConfig) -> str:
    flags = " ".join(config.compiler_flags)
    # Bake the config's PPA criteria into the `make ppa` target so the iterate loop
    # (edit RTL/source -> make ppa -> read slack headroom) needs no re-typed flags and
    # no external config file — every declared criterion is enforced, not just slack.
    ppa_flags = f"--node {config.node} --clock {config.clock}"
    if config.min_slack is not None:
        ppa_flags += f" --min-slack {config.min_slack}"
    if config.max_area_um2 is not None:
        ppa_flags += f" --max-area {config.max_area_um2}"
    if config.max_power_w is not None:
        ppa_flags += f" --max-power {config.max_power_w}"
    if config.max_latency_cycles is not None:
        ppa_flags += f" --max-latency {config.max_latency_cycles}"
    if config.top:
        ppa_flags += f" --top {config.top}"
    vitis_command = shlex.join(vitis_tcl_command(config.vitis_bin, "run_hls.tcl"))
    return f"""CXX ?= g++
PYTHON ?= python3
CXXFLAGS ?= -std=c++17 -Wall -Wextra -I src {flags}
TB_EXE ?= c2hlsc_tb
LEVERI_GOLDEN_EXE ?= leveri_golden_tb
LEVERI_HLS_EXE ?= leveri_hls_tb
RTL_VECTORS_EXE ?= rtl_vectors_tb

.PHONY: all test leveri-test gcov-coverage klee-coverage coverage \\
        rtl-vectors rtl-testbench rtl-cosim ppa clean vitis

all: test

$(TB_EXE): tb/testbench.cpp src/hls_top.cpp src/hls_top.hpp input.c
\t"$(CXX)" $(CXXFLAGS) tb/testbench.cpp src/hls_top.cpp -o $(TB_EXE)

$(LEVERI_GOLDEN_EXE): tb/leveri_golden_tb.cpp input.c
\t"$(CXX)" $(CXXFLAGS) tb/leveri_golden_tb.cpp -o $(LEVERI_GOLDEN_EXE)

$(LEVERI_HLS_EXE): tb/leveri_hls_tb.cpp src/hls_top.cpp src/hls_top.hpp
\t"$(CXX)" $(CXXFLAGS) tb/leveri_hls_tb.cpp src/hls_top.cpp -o $(LEVERI_HLS_EXE)

test: $(TB_EXE)
\t./$(TB_EXE)

leveri-test: $(LEVERI_GOLDEN_EXE) $(LEVERI_HLS_EXE)
\t./$(LEVERI_GOLDEN_EXE)
\t./$(LEVERI_HLS_EXE)
\t"$(PYTHON)" tb/leveri_compare.py leveri_golden_trace.csv leveri_hls_trace.csv

gcov-coverage:
\t"$(PYTHON)" tb/run_gcov.py

klee-coverage:
\t"$(PYTHON)" tb/run_klee.py

coverage: gcov-coverage klee-coverage

# Standalone RTL (Verilog) testbench flow. Produces golden expected vectors from the
# original C, renders a self-checking testbench, and (post-synthesis) simulates the RTL.
$(RTL_VECTORS_EXE): tb/rtl_vectors_tb.cpp input.c
\t"$(CXX)" $(CXXFLAGS) tb/rtl_vectors_tb.cpp -o $(RTL_VECTORS_EXE)

rtl-vectors: $(RTL_VECTORS_EXE)
\tmkdir -p rtl_vectors
\t./$(RTL_VECTORS_EXE)

rtl-testbench:
\t"$(PYTHON)" tb/gen_rtl_tb.py --from-contract

rtl-cosim:
\t"$(PYTHON)" tb/run_rtl_sim.py

# PPA workflow criteria: yosys + OpenSTA on the project's RTL, measured on the
# configured process node; prints the slack headroom (iteration budget) and exits
# nonzero when a declared criterion (e.g. min_slack) is unmet. Needs the
# c2hlsc_agent package importable plus yosys/OpenSTA; liberties auto-download.
ppa:
\t"$(PYTHON)" -m c2hlsc_agent.cli ppa --project . {ppa_flags}

# run_all.sh invokes this native launcher and applies the positive CoSim evidence
# gate: {vitis_command}
vitis:
\tbash run_all.sh --vitis-only

clean:
\trm -f $(TB_EXE) $(LEVERI_GOLDEN_EXE) $(LEVERI_HLS_EXE) $(RTL_VECTORS_EXE)
\trm -f leveri_golden_trace.csv leveri_hls_trace.csv
\trm -rf coverage rtl_vectors
\trm -f tb/*_tb.sv
\trm -f *.gcda *.gcno *.gcov
\trm -rf c2hlsc_project
"""


def render_run_all(config: AgentConfig | None = None) -> str:
    config = config or AgentConfig()
    executable = shlex.quote(config.vitis_bin)
    command = shlex.join(vitis_tcl_command(config.vitis_bin, "run_hls.tcl"))
    return f"""#!/usr/bin/env bash
set -euo pipefail

VITIS_LOG="${{VITIS_LOG:-vitis_hls_run.log}}"

gate_cosim_log() {{
  local log="$1"
  if grep -qiE 'co-simulation finished: fail|cosim design failed|co-simulation failed|aborting co-simulation|aborting cosim|error: \\[(cosim|sim)|mismatch test=' "$log"; then
    echo "CoSim gate: FAIL - $log reports a co-simulation failure." >&2
    return 1
  fi
  if ! grep -qi 'co-simulation finished: pass' "$log"; then
    echo "CoSim gate: FAIL - $log carries no positive C/RTL co-simulation PASS verdict." >&2
    return 1
  fi
  echo "CoSim gate: PASS ($log)."
}}

vitis_only=0
if [ "${{1:-}}" = "--vitis-only" ]; then
  vitis_only=1
else
  make test
fi

if command -v {executable} >/dev/null 2>&1; then
  {command} 2>&1 | tee "$VITIS_LOG"
  gate_cosim_log "$VITIS_LOG"
elif [ "$vitis_only" = "1" ]; then
  echo "Vitis HLS launcher not found; the requested Vitis ladder did not run." >&2
  exit 127
else
  echo "Vitis HLS launcher not found; host equivalence completed, Vitis phases skipped." >&2
fi
"""


def write_project(out_dir: Path, analysis: AnalysisResult, generated: GeneratedSource, config: AgentConfig) -> ProjectFiles:
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "src").mkdir(exist_ok=True)
    (out_dir / "tb").mkdir(exist_ok=True)
    leveri_bundle = generate_leveri_testbenches(analysis, config, generated.source)
    verilog_bundle = generate_verilog_testbenches(analysis, config)
    shutil.copyfile(analysis.function.source_path, out_dir / "input.c")
    files = [
        out_dir / "input.c",
        out_dir / "src" / "hls_top.hpp",
        out_dir / "src" / "hls_top.cpp",
        out_dir / "tb" / "testbench.cpp",
        out_dir / "tb" / "leveri_golden_tb.cpp",
        out_dir / "tb" / "leveri_hls_tb.cpp",
        out_dir / "tb" / "leveri_compare.py",
        out_dir / "tb" / "run_gcov.py",
        out_dir / "tb" / "klee_driver.cpp",
        out_dir / "tb" / "run_klee.py",
        out_dir / "tb" / "leveri_manifest.json",
        out_dir / "tb" / "rtl_vectors_tb.cpp",
        out_dir / "tb" / "gen_rtl_tb.py",
        out_dir / "tb" / "run_rtl_sim.py",
        out_dir / "tb" / "rtl_tb_manifest.json",
        out_dir / "run_hls.tcl",
        out_dir / "run_csim.tcl",
        out_dir / "run_csynth.tcl",
        out_dir / "run_cosim.tcl",
        out_dir / "Makefile",
        out_dir / "run_all.sh",
    ]
    (out_dir / "src" / "hls_top.hpp").write_text(generated.header, encoding="utf-8")
    (out_dir / "src" / "hls_top.cpp").write_text(generated.source, encoding="utf-8")
    (out_dir / "tb" / "testbench.cpp").write_text(generate_testbench(analysis, config), encoding="utf-8")
    (out_dir / "tb" / "leveri_golden_tb.cpp").write_text(leveri_bundle.golden_tb, encoding="utf-8")
    (out_dir / "tb" / "leveri_hls_tb.cpp").write_text(leveri_bundle.hls_tb, encoding="utf-8")
    (out_dir / "tb" / "leveri_compare.py").write_text(leveri_bundle.compare_script, encoding="utf-8")
    (out_dir / "tb" / "run_gcov.py").write_text(leveri_bundle.gcov_script, encoding="utf-8")
    (out_dir / "tb" / "klee_driver.cpp").write_text(leveri_bundle.klee_driver, encoding="utf-8")
    (out_dir / "tb" / "run_klee.py").write_text(leveri_bundle.klee_script, encoding="utf-8")
    (out_dir / "tb" / "leveri_manifest.json").write_text(leveri_bundle.manifest_json, encoding="utf-8")
    (out_dir / "tb" / "rtl_vectors_tb.cpp").write_text(verilog_bundle.vectors_tb, encoding="utf-8")
    (out_dir / "tb" / "gen_rtl_tb.py").write_text(verilog_bundle.gen_script, encoding="utf-8")
    (out_dir / "tb" / "run_rtl_sim.py").write_text(verilog_bundle.run_script, encoding="utf-8")
    (out_dir / "tb" / "rtl_tb_manifest.json").write_text(verilog_bundle.manifest_json, encoding="utf-8")
    (out_dir / "run_hls.tcl").write_text(render_run_hls(analysis, config), encoding="utf-8")
    (out_dir / "run_csim.tcl").write_text(render_run_csim(analysis, config), encoding="utf-8")
    (out_dir / "run_csynth.tcl").write_text(render_run_csynth(), encoding="utf-8")
    (out_dir / "run_cosim.tcl").write_text(render_run_cosim(config), encoding="utf-8")
    (out_dir / "Makefile").write_text(render_makefile(config), encoding="utf-8")
    run_all = out_dir / "run_all.sh"
    run_all.write_text(render_run_all(config), encoding="utf-8")
    run_all.chmod(run_all.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)
    leveri_compare = out_dir / "tb" / "leveri_compare.py"
    leveri_compare.chmod(leveri_compare.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)
    for script_name in ("run_gcov.py", "run_klee.py", "gen_rtl_tb.py", "run_rtl_sim.py"):
        script = out_dir / "tb" / script_name
        script.chmod(script.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)
    return ProjectFiles(out_dir, files)
