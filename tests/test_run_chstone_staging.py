class MutantSourceTest(unittest.TestCase):
    def test_wraps_the_top_and_perturbs_the_returned_value(self) -> None:
        candidate = '#include "hls_top.hpp"\n\nint chstone_main() {\n  return 0;\n}\n'
        source, changed = chstone_staging.render_mutant_source(candidate, TOP)
        self.assertTrue(changed)
        self.assertIn("int chstone_main_c2hlsc_premutation() {", source)
        self.assertIn("int chstone_main() { return chstone_main_c2hlsc_premutation() + 1; }", source)

    def test_leaves_the_repair_agents_rename_directives_alone(self) -> None:
        # The repair agent renames the top before #including the original sources. Rewriting
        # those two directives would let input.c define chstone_main at global scope and the
        # mutant would fail to link -- which the harness would then have to score as
        # inconclusive, losing the evidence.
        candidate = textwrap.dedent(
            """\
            #include "hls_top.hpp"
            #define chstone_main chstone_main_c2hlsc_repair_reference
            #include "../input.c"
            #undef chstone_main

            int chstone_main() { return chstone_main_c2hlsc_repair_reference(); }
            """
        )
        source, changed = chstone_staging.render_mutant_source(candidate, TOP)
        self.assertTrue(changed)
        self.assertIn("#define chstone_main chstone_main_c2hlsc_repair_reference", source)
        self.assertIn("#undef chstone_main", source)
        self.assertIn("int chstone_main() { return chstone_main_c2hlsc_premutation() + 1; }", source)

    def test_reports_no_change_when_the_top_is_absent(self) -> None:
        source, changed = chstone_staging.render_mutant_source("int other() { return 0; }\n", TOP)
        self.assertFalse(changed)
        self.assertNotIn("premutation", source)

    def test_write_mutant_source_returns_none_without_a_candidate(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            self.assertIsNone(chstone_staging.write_mutant_source(Path(tmp), TOP))


