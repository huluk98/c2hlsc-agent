"""Tests for the CHStone staging fix and the ablation knobs that sit on top of it.

Three layers, deliberately:

*unit*
    :mod:`c2hlsc_agent.chstone_staging` rewrites two files the converter emits
    (``tb/testbench.cpp`` and ``Makefile``) by pattern. If ``testgen``/``hls_project`` ever
    change their output, the rewrites must degrade to "not applied" rather than silently
    produce something subtly wrong, so every rewrite is tested for both the hit and the miss.

*integration, with a real toolchain*
    A synthetic benchmark that reproduces the exact C89 constructs that block CHStone --
    K&R parameter definitions, a tentative definition redeclared at file scope, an ``int``
    array initialised from unsigned literals, and a file-scope global the candidate also
    defines -- is pushed through the *real* converter, staged, built and run. Then the
    candidate is mutated and the same test must go red. Skipped when gcc/g++/objcopy/make
    are unavailable; never faked.

*arm bookkeeping*
    The knobs an ablation is read from (``--repair-rounds`` vs ``--max-iterations``,
    ``--legacy-staging``) and the reachable-vs-passed accounting, because an arm whose
    configuration is misrecorded produces a table nobody can trust.
"""

