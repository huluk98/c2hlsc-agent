class StagedVerdictAuthorityTest(unittest.TestCase):
    """The staged flow must score the STAGED log, never ``conversion_report.json``.

    Phase 1 of the staged flow runs ``convert`` once, which verifies the project *before*
    the staging lands. Its ``conversion_report.json`` therefore describes a different build.
    For most CHStone benchmarks that stale field says "fail" and is harmless, but a
    benchmark that passed unstaged and then fails to link once the real golden object is
    added would be reported green off the stale field. These tests pin that shut.
    """

    def _run(self, make_result: tuple[int, str], report: dict) -> object:
        tmp = tempfile.TemporaryDirectory()
        self.addCleanup(tmp.cleanup)
        root = Path(tmp.name)
        source = root / "bench"
        source.mkdir()
        (source / "top.c").write_text(SYNTHETIC_TOP, encoding="utf-8")
        bench = driver.ChstoneBenchmark("synthetic", source, source / "top.c")
        out_dir = root / "out"

        def fake_convert(cmd, **kwargs):
            project = out_dir / "benchmarks" / "synthetic" / "project"
            project.parent.mkdir(parents=True, exist_ok=True)
            _fake_project(project.parent)
            import json as _json
            (project / "conversion_report.json").write_text(_json.dumps(report), encoding="utf-8")
            return subprocess.CompletedProcess(cmd, 0, "", "")

        args = _args(auto_repair=False, repair_rounds=0, mutation_check=False)
        args.timeout = 60
        with mock.patch.object(driver.subprocess, "run", side_effect=fake_convert), \
             mock.patch.object(driver, "_make", return_value=make_result):
            return driver.run_agent_staged(bench, out_dir, args)

    def test_stale_pass_in_the_conversion_report_cannot_make_a_failed_link_green(self) -> None:
        row = self._run(
            (1, "/usr/bin/ld: multiple definition of `main_result'\n"),
            {"software_equivalence": "pass",
             "phases": {"software_equivalence": {"name": "software_equivalence", "status": "pass"}}},
        )
        self.assertFalse(row.ok)
        self.assertEqual(row.rung, "generated")
        self.assertEqual(row.failure_family, "golden_candidate_symbol_collision")
        self.assertIsNone(row.stimulus_count)

    def test_a_real_pass_records_the_stimulus_count_it_reported(self) -> None:
        row = self._run(
            (0, "c2hlsc_agent: all 100 tests passed, seed=1\n"),
            {"software_equivalence": "fail"},
        )
        self.assertTrue(row.ok)
        self.assertEqual(row.rung, "host_equivalence")
        self.assertEqual(row.stimulus_count, 100)
        self.assertEqual(row.staging, "golden_c_tu")
        self.assertEqual(row.repair_rounds_allowed, 0)


