class RepairRoundsTest(unittest.TestCase):
    def test_max_iterations_keeps_its_cli_meaning(self) -> None:
        # `convert --max-iterations N` is N verification attempts, so N-1 repairs. The
        # default of 2 is what every published CHStone number was measured under; changing
        # this mapping silently would make old and new arms incomparable.
        self.assertEqual(driver.repair_rounds(_args(auto_repair=True, max_iterations=2)), 1)
        self.assertEqual(driver.repair_rounds(_args(auto_repair=True, max_iterations=4)), 3)
        self.assertEqual(driver.repair_rounds(_args(auto_repair=True, max_iterations=1)), 0)
        self.assertEqual(driver.repair_rounds(_args(auto_repair=True, max_iterations=0)), 0)

    def test_repair_rounds_spelling_wins_when_given(self) -> None:
        for rounds in (0, 1, 2, 3):
            self.assertEqual(
                driver.repair_rounds(_args(auto_repair=True, repair_rounds=rounds, max_iterations=99)),
                rounds,
            )

    def test_no_repair_without_auto_repair(self) -> None:
        self.assertEqual(driver.repair_rounds(_args(auto_repair=False, max_iterations=4)), 0)
        self.assertEqual(driver.repair_rounds(_args(auto_repair=False, repair_rounds=3)), 0)

    def test_arm_descriptor_records_what_would_change_the_number(self) -> None:
        arm = driver.arm_descriptor(_args(auto_repair=True, repair_rounds=2, use_llm=True,
                                          llm_model="opus", label="llm_r2"))
        self.assertEqual(arm["label"], "llm_r2")
        self.assertEqual(arm["generator"], "llm")
        self.assertEqual(arm["staging"], "golden_c_tu")
        self.assertEqual(arm["repair_rounds_allowed"], 2)
        legacy = driver.arm_descriptor(_args(staged=False))
        self.assertEqual(legacy["staging"], "legacy_inline")
        # The narrowing relaxation and the mutation check only exist in the staged flow;
        # reporting them as on for a legacy arm would describe a run that did not happen.
        self.assertFalse(legacy["relax_narrowing"])
        self.assertFalse(legacy["mutation_check"])


