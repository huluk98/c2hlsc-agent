        # The same C89 constructs, but reached through the candidate's own translation unit,
        # are the converter's problem. Folding them into the harness bucket would let the
        # deterministic arm hide its failures behind the staging fix.
        rows = [self._row("motion", False, "candidate_includes_original_c")]
        summary = driver._summarise(rows, "agent", 1.0, 1, arm={})
        self.assertEqual(summary["reachable"], 1)
        self.assertEqual(summary["passed_of_reachable"], 0)
        self.assertEqual(summary["unreachable"], [])


