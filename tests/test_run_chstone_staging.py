#: Exactly what c2hlsc_agent.testgen emits for a nullary int top.
TESTBENCH = textwrap.dedent(
    """\
    // Generated by c2hlsc_agent. This file is testbench-only code.
    #include <iostream>

    extern "C" {
    #define restrict __restrict__
    #define chstone_main chstone_main_ref
    #include "../input.c"
    #undef chstone_main
    }

    #include "../src/hls_top.hpp"

    int main() {
      for (int test_idx = 0; test_idx < 100; ++test_idx) {

        int ref_ret = chstone_main_ref();
        int hls_ret = chstone_main();
      }
      std::cout << "c2hlsc_agent: all 100 tests passed, seed=1\\n";
      return 0;
    }
    """
)


class RewriteTestbenchTest(unittest.TestCase):
    def test_replaces_inlined_golden_with_a_declaration(self) -> None:
        new_text, changed = chstone_staging.rewrite_testbench(TESTBENCH, TOP)
        self.assertTrue(changed)
        self.assertNotIn('#include "../input.c"', new_text)
        self.assertIn('extern "C" int chstone_main_ref(void);', new_text)
        # The call site and the rest of the testbench are untouched: the oracle did not
        # change, only how it is built.
        self.assertIn("int ref_ret = chstone_main_ref();", new_text)
        self.assertIn("int hls_ret = chstone_main();", new_text)
        self.assertIn("all 100 tests passed", new_text)

    def test_declaration_uses_the_return_type_the_testbench_actually_calls_with(self) -> None:
        text = TESTBENCH.replace("int ref_ret", "long ref_ret").replace("int hls_ret", "long hls_ret")
        new_text, changed = chstone_staging.rewrite_testbench(text, TOP)
        self.assertTrue(changed)
        self.assertIn('extern "C" long chstone_main_ref(void);', new_text)

    def test_refuses_a_top_that_takes_arguments(self) -> None:
        # This staging links a single nullary symbol. A top with arguments is not a CHStone
        # top, and guessing a signature here would produce a link that compiles and lies.
        text = TESTBENCH.replace("chstone_main_ref();", "chstone_main_ref(ref_a, 3);")
        _, changed = chstone_staging.rewrite_testbench(text, TOP)
        self.assertFalse(changed)

    def test_refuses_when_the_expected_block_is_absent(self) -> None:
        text = TESTBENCH.replace('#include "../input.c"', '#include "../somewhere_else.c"')
        new_text, changed = chstone_staging.rewrite_testbench(text, TOP)
        self.assertFalse(changed)
        self.assertEqual(new_text, text)

    def test_ignores_an_unrelated_extern_c_block(self) -> None:
        text = TESTBENCH.replace(
            'extern "C" {\n#define restrict',
            'extern "C" {\nvoid unrelated(void);\n}\n\nextern "C" {\n#define restrict',
        )
        new_text, changed = chstone_staging.rewrite_testbench(text, TOP)
        self.assertTrue(changed)
        self.assertIn("void unrelated(void);", new_text)
        self.assertNotIn('#include "../input.c"', new_text)


