def _fake_project(root: Path) -> Path:
    from c2hlsc_agent.config import AgentConfig
    from c2hlsc_agent.hls_project import render_makefile

    project = root / "project"
    (project / "tb").mkdir(parents=True)
    (project / "src").mkdir()
    (project / "input.c").write_text("int chstone_main(void) { return 0; }\n", encoding="utf-8")
    (project / "tb" / "testbench.cpp").write_text(TESTBENCH, encoding="utf-8")
    (project / "Makefile").write_text(render_makefile(AgentConfig()), encoding="utf-8")
    (project / "src" / "hls_top.cpp").write_text("int chstone_main() { return 0; }\n", encoding="utf-8")
    return project


class StageProjectTest(unittest.TestCase):
    def test_stages_siblings_without_clobbering_or_copying_the_top(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            source = root / "bench"
            source.mkdir()
            (source / "top.c").write_text("top\n", encoding="utf-8")
            (source / "helper.c").write_text("helper\n", encoding="utf-8")
            (source / "hls.tcl").write_text("tcl\n", encoding="utf-8")
            (source / "keep.h").write_text("fresh\n", encoding="utf-8")
            project = root / "project"
            project.mkdir()
            (project / "keep.h").write_text("already staged\n", encoding="utf-8")

            copied = chstone_staging.stage_sibling_sources(project, source, "top.c")

            self.assertEqual(copied, ["helper.c"])
            self.assertFalse((project / "top.c").exists())
            self.assertFalse((project / "hls.tcl").exists())
            self.assertEqual((project / "keep.h").read_text(encoding="utf-8"), "already staged\n")

    def test_end_to_end_rewrites_and_is_idempotent(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            source = root / "bench"
            source.mkdir()
            (source / "top.c").write_text("top\n", encoding="utf-8")
            project = _fake_project(root)

            first = chstone_staging.stage_project(project, source, "top.c", TOP)
            self.assertTrue(first.applied)
            self.assertEqual(first.golden_export, "chstone_main_ref")
            golden = (project / "golden_ref.c").read_text(encoding="utf-8")
            self.assertIn("#define chstone_main chstone_main_ref", golden)
            self.assertIn('#include "input.c"', golden)

            tb_after_first = (project / "tb" / "testbench.cpp").read_text(encoding="utf-8")
            mk_after_first = (project / "Makefile").read_text(encoding="utf-8")

            second = chstone_staging.stage_project(project, source, "top.c", TOP)
            self.assertTrue(second.applied)
            self.assertEqual(
                (project / "tb" / "testbench.cpp").read_text(encoding="utf-8"), tb_after_first
            )
            self.assertEqual((project / "Makefile").read_text(encoding="utf-8"), mk_after_first)

    def test_reports_why_it_declined_instead_of_half_applying(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            source = root / "bench"
            source.mkdir()
            project = _fake_project(root)
            (project / "tb" / "testbench.cpp").write_text("int main(){return 0;}\n", encoding="utf-8")

            result = chstone_staging.stage_project(project, source, "top.c", TOP)

            self.assertFalse(result.applied)
            self.assertIsNotNone(result.skipped_reason)
            # Declining must not leave a golden_ref.c behind that nothing links.
            self.assertFalse((project / "golden_ref.c").exists())

    def test_missing_project_is_reported_not_raised(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            result = chstone_staging.stage_project(
                Path(tmp) / "nope", Path(tmp), "top.c", TOP
            )
            self.assertFalse(result.applied)
            self.assertIn("missing", (result.skipped_reason or ""))


# --------------------------------------------------------------------------- #
# the -Wno-narrowing justification, checked rather than asserted in prose
# --------------------------------------------------------------------------- #

_NARROWING_SOURCE = """\
unsigned char probe[16] = {0};
int table[4] = {0, 0xffffffff, 0xfffffffe, 0x80000000};
"""


@unittest.skipUnless(HAVE_TOOLCHAIN, "needs gcc/g++/objcopy/make")
class NarrowingRelaxationTest(unittest.TestCase):
    """``-Wno-narrowing`` must be a diagnostic switch, not a codegen switch.

    CHStone initialises ``int`` arrays from unsigned literals. If suppressing the C++
    narrowing diagnostic changed the stored values, the staging would be altering the
    program under test. It does not, and this proves it by comparing the emitted bytes of
    the same initialiser built as C and as C++.
    """

    def _table_bytes(self, tmp: Path, name: str, compiler: str, flags: list[str]) -> bytes:
        source = tmp / name
        source.write_text(_NARROWING_SOURCE, encoding="utf-8")
        obj = tmp / (name + ".o")
        build = subprocess.run(
            [compiler, *flags, "-c", str(source), "-o", str(obj)],
            capture_output=True, text=True,
        )
        self.assertEqual(build.returncode, 0, build.stderr)
        dump = tmp / (name + ".bin")
        subprocess.run(
            ["objcopy", "-O", "binary", "--only-section=.data", str(obj), str(dump)],
            check=True, capture_output=True,
        )
        return dump.read_bytes()

    def test_cpp_narrowing_is_an_error_without_the_flag(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            source = Path(tmp) / "strict.cpp"
            source.write_text(_NARROWING_SOURCE, encoding="utf-8")
            build = subprocess.run(
                ["g++", "-std=c++17", "-c", str(source), "-o", str(Path(tmp) / "strict.o")],
                capture_output=True, text=True,
            )
            self.assertNotEqual(build.returncode, 0)
            self.assertIn("narrowing", build.stderr)

    def test_relaxed_cpp_emits_the_same_bytes_as_c(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            as_c = self._table_bytes(root, "ref.c", "gcc", ["-O1"])
            as_cpp = self._table_bytes(
                root, "relaxed.cpp", "g++", ["-std=c++17", "-O1", "-Wno-narrowing"]
            )
            self.assertEqual(as_c, as_cpp)
            self.assertTrue(as_c, "expected the initialiser to land in .data")


# --------------------------------------------------------------------------- #
# integration: a synthetic benchmark with every blocking construct
# --------------------------------------------------------------------------- #

#: Reproduces, in ~40 lines, exactly what blocks CHStone under the legacy staging:
#:   * a K&R parameter definition (blowfish, motion)
#:   * a tentative definition redeclared at file scope (jpeg)
#:   * a ``register`` declaration (jpeg)
#:   * an ``int`` table initialised from unsigned literals (adpcm, jpeg)
#:   * a file-scope global the candidate will also define (mips, sha: the collision)
SYNTHETIC_TOP = """\
#include <stdio.h>

int main_result;
int main_result;

int mask_table[4] = {0, 0xffffffff, 0xfffffffe, 0x80000000};

int accumulate ();

int
accumulate (n)
     int n;
{
  register int i;
  int total = 0;
  for (i = 0; i < n; i++)
    total += mask_table[i & 3];
  return total;
}

int
main ()
{
  main_result = 0;
  if (accumulate (8) != -6)
    main_result += 1;
  printf ("%d\\n", main_result);
  return main_result;
}
"""


@unittest.skipUnless(HAVE_TOOLCHAIN, "needs gcc/g++/objcopy/make")
class StagedEquivalenceIntegrationTest(unittest.TestCase):
    """Build a real project through the real converter, stage it, run it, then mutate it.

    This is the test that would catch a false green: if the staged equivalence binary
    passed against a candidate whose returned value is deliberately wrong, the CHStone
    numbers would be meaningless.
    """

    def _build_project(self, root: Path) -> tuple[Path, Path]:
        from c2hlsc_agent.analyze import analyze_source
        from c2hlsc_agent.config import AgentConfig
        from c2hlsc_agent.convert import generate_hls_sources
        from c2hlsc_agent.hls_project import write_project

        source_dir = root / "bench"
        source_dir.mkdir()
        top_file = source_dir / "top.c"
        renamed, count = driver.rename_main(SYNTHETIC_TOP)
        self.assertEqual(count, 1)
        top_file.write_text(renamed, encoding="utf-8")

        config = AgentConfig()
        config.num_tests = 5
        analysis = analyze_source(top_file, TOP, config)
        generated = generate_hls_sources(analysis, config, llm=None)
        project = root / "project"
        write_project(project, analysis, generated, config)
        return source_dir, project

    def test_legacy_staging_cannot_even_build_this(self) -> None:
        # The control: without the fix, the C89 above never reaches a verdict, and the error
        # is in the golden reference the harness inlined -- not in the candidate.
        with tempfile.TemporaryDirectory() as tmp:
            _, project = self._build_project(Path(tmp))
            build = subprocess.run(["make", "test"], cwd=project, capture_output=True, text=True)
            self.assertNotEqual(build.returncode, 0)
            combined = build.stdout + build.stderr
            self.assertIn("error:", combined)
            self.assertIn("tb/../input.c", combined)

    #: A self-contained C++ translation of the same kernel -- the shape the LLM generator
    #: actually emits, and the shape that only becomes measurable once the golden reference
    #: stops being compiled by g++.
    CANDIDATE_CPP = textwrap.dedent(
        """\
        #include "hls_top.hpp"
        #include <cstdio>

        namespace {
        const int kMask[4] = {0, -1, -2, -2147483648};
        int candidate_accumulate(int n) {
          int total = 0;
          for (int i = 0; i < n; ++i) total += kMask[i & 3];
          return total;
        }
        }  // namespace

        int chstone_main() {
          int result = 0;
          if (candidate_accumulate(8) != -6) result += 1;
          std::printf("%d\\n", result);
          return result;
        }
        """
    )

    def test_staged_project_passes_and_the_mutant_goes_red(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            source_dir, project = self._build_project(Path(tmp))

            staged = chstone_staging.stage_project(project, source_dir, "top.c", TOP)
            self.assertTrue(staged.applied, staged.skipped_reason)
            (project / "src" / "hls_top.cpp").write_text(self.CANDIDATE_CPP, encoding="utf-8")

            run = subprocess.run(["make", "test"], cwd=project, capture_output=True, text=True)
            combined = run.stdout + run.stderr
            self.assertEqual(run.returncode, 0, combined)
            self.assertIn("all 5 tests passed", combined)
            self.assertEqual(driver._stimulus_count(combined), 5)

            # Exactly one symbol leaves the golden object, so its file-scope state can
            # neither collide with the candidate's nor be silently shared with it. Sharing
            # would be the worse failure: the two sides would agree by construction.
            symbols = subprocess.run(
                ["nm", "--defined-only", "-g", "golden_ref.o"],
                cwd=project, capture_output=True, text=True, check=True,
            ).stdout.split()
            self.assertIn("chstone_main_ref", symbols)
            self.assertNotIn("main_result", symbols)
            self.assertNotIn("mask_table", symbols)

            verdict, detail = driver.run_mutation_check(project, timeout=120)
            self.assertEqual(verdict, "red", detail)
            self.assertIn("Mismatch test=", detail)

    def test_a_candidate_that_reincludes_the_c89_fails_on_its_own_translation_unit(self) -> None:
        # This is blowfish/motion under the staged flow. The staging fixed the golden side,
        # and what is left is the deterministic converter's own strategy -- pulling C89 into
        # a C++ TU -- failing. It must be scored, with the error attributed to src/, not tb/.
        with tempfile.TemporaryDirectory() as tmp:
            source_dir, project = self._build_project(Path(tmp))
            chstone_staging.stage_project(project, source_dir, "top.c", TOP)
            (project / "src" / "hls_top.cpp").write_text(
                '#include "hls_top.hpp"\n'
                f"#define {TOP} {TOP}_c2hlsc_repair_reference\n"
                '#include "../input.c"\n'
                f"#undef {TOP}\n\n"
                f"int {TOP}() {{ return {TOP}_c2hlsc_repair_reference(); }}\n",
                encoding="utf-8",
            )
            run = subprocess.run(["make", "test"], cwd=project, capture_output=True, text=True)
            combined = run.stdout + run.stderr
            self.assertNotEqual(run.returncode, 0)
            self.assertIn("src/../input.c", combined)
            self.assertNotIn("tb/../input.c", combined)
            rung, family = driver._classify_conversion(
                {"software_equivalence": "fail"}, combined
            )
            self.assertEqual((rung, family), ("generated", "candidate_includes_original_c"))

    def test_strict_narrowing_arm_shows_the_flag_is_load_bearing(self) -> None:
        # A candidate whose ONLY C++ problem is a narrowing initialiser: it builds under the
        # default arm and fails under --strict-narrowing. That is the whole cost of the flag,
        # measured rather than asserted.
        candidate = (
            '#include "hls_top.hpp"\n'
            "static const int kMask[4] = {0, 0xffffffff, 0xfffffffe, 0x80000000};\n"
            "int chstone_main() { int t = 0; for (int i = 0; i < 8; ++i) t += kMask[i & 3];"
            " return t != -6; }\n"
        )
        for relax, expect_ok in ((True, True), (False, False)):
            with self.subTest(relax_narrowing=relax), tempfile.TemporaryDirectory() as tmp:
                source_dir, project = self._build_project(Path(tmp))
                chstone_staging.stage_project(
                    project, source_dir, "top.c", TOP, relax_narrowing=relax
                )
                (project / "src" / "hls_top.cpp").write_text(candidate, encoding="utf-8")
                run = subprocess.run(["make", "test"], cwd=project, capture_output=True, text=True)
                combined = run.stdout + run.stderr
                if expect_ok:
                    self.assertEqual(run.returncode, 0, combined)
                    self.assertIn("all 5 tests passed", combined)
                else:
                    self.assertNotEqual(run.returncode, 0)
                    self.assertIn("narrowing", combined)
                    self.assertIn("src/hls_top.cpp", combined)


