class RewriteMakefileTest(unittest.TestCase):
    def setUp(self) -> None:
        from c2hlsc_agent.config import AgentConfig
        from c2hlsc_agent.hls_project import render_makefile

        # The real Makefile, so a change in hls_project.render_makefile fails this test
        # instead of silently disabling the staging in production.
        self.makefile = render_makefile(AgentConfig())

    def test_links_a_separately_compiled_golden_object(self) -> None:
        new_text, changed = chstone_staging.rewrite_makefile(self.makefile, TOP, relax_narrowing=False)
        self.assertTrue(changed)
        self.assertIn("$(CC) $(GOLDEN_CFLAGS) -c golden_ref.c -o $(GOLDEN_OBJ)", new_text)
        self.assertIn("--keep-global-symbol=$(GOLDEN_EXPORT)", new_text)
        self.assertIn("GOLDEN_EXPORT ?= chstone_main_ref", new_text)
        # The testbench binary now links the golden object instead of compiling input.c.
        self.assertIn(
            "$(CXX) $(CXXFLAGS) tb/testbench.cpp src/hls_top.cpp $(GOLDEN_OBJ) -o $(TB_EXE)",
            new_text,
        )
        self.assertIn("mutation-check:", new_text)
        self.assertNotIn(
            "$(CXX) $(CXXFLAGS) tb/testbench.cpp src/hls_top.cpp -o $(TB_EXE)", new_text
        )

    def test_narrowing_relaxation_is_opt_out_and_documented(self) -> None:
        relaxed, _ = chstone_staging.rewrite_makefile(self.makefile, TOP, relax_narrowing=True)
        strict, _ = chstone_staging.rewrite_makefile(self.makefile, TOP, relax_narrowing=False)
        self.assertIn("CXXFLAGS += -Wno-narrowing", relaxed)
        self.assertIn(chstone_staging.narrowing_relaxation_note(), relaxed)
        self.assertNotIn("-Wno-narrowing", strict)

    def test_refuses_when_the_rule_is_absent(self) -> None:
        text = self.makefile.replace("$(TB_EXE): tb/testbench.cpp", "$(TB_EXE): tb/other.cpp")
        new_text, changed = chstone_staging.rewrite_makefile(text, TOP, relax_narrowing=True)
        self.assertFalse(changed)
        self.assertEqual(new_text, text)


