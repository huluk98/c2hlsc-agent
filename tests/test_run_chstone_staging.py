class MutationVerdictTest(unittest.TestCase):
    def _check(self, make_result: tuple[int, str], *, mutant: bool = True) -> tuple[str, str]:
        with mock.patch.object(chstone_staging, "write_mutant_source",
                               return_value=Path("src/hls_top_mutant.cpp") if mutant else None), \
             mock.patch.object(driver.chstone_staging, "write_mutant_source",
                               return_value=Path("src/hls_top_mutant.cpp") if mutant else None), \
             mock.patch.object(driver, "_make", return_value=make_result):
            return driver.run_mutation_check(Path("/nonexistent"), timeout=10)

    def test_mismatch_line_is_the_only_thing_that_counts_as_red(self) -> None:
        verdict, detail = self._check((1, "Mismatch test=0 return expected=0 actual=1 seed=1\n"))
        self.assertEqual(verdict, "red")
        self.assertIn("Mismatch test=0", detail)

    def test_a_mutant_that_fails_to_compile_is_inconclusive_not_red(self) -> None:
        # This is the trap: a nonzero exit code from a build failure looks exactly like a
        # caught mutation if you only check the return code.
        verdict, detail = self._check((2, "src/hls_top_mutant.cpp:9:1: error: redefinition\n"))
        self.assertEqual(verdict, "inconclusive")
        self.assertIn("error", detail)

    def test_a_surviving_mutant_is_flagged_as_a_false_green(self) -> None:
        verdict, _ = self._check((0, "c2hlsc_agent: all 100 tests passed, seed=1\n"))
        self.assertEqual(verdict, "FALSE_GREEN")

    def test_unwrappable_candidate_is_inconclusive(self) -> None:
        verdict, detail = self._check((0, ""), mutant=False)
        self.assertEqual(verdict, "inconclusive")
        self.assertIn("could not rename", detail)

    def test_timeout_is_inconclusive(self) -> None:
        verdict, _ = self._check((124, "make mutation-check timed out after 10s"))
        self.assertEqual(verdict, "inconclusive")


